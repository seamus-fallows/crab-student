from crab_student import core

REMOTE_DIR = "/root/crab-student"
PY = 'exec "$(command -v python3 || echo /venv/main/bin/python)"'
REMOTE_SRC = Path(__file__).parent / "remote"
ALIAS_PREFIX = "crab-student-"  # (agents' ssh host names)
REMOTE_PLATFORM = "remote.SSH.remotePlatform"  # (VS Code: which hosts run Linux)
CLAUDE_URL = "vscode://anthropic.claude-code/open?prompt="  # (the Claude extension's panel, pre-filled)
PROMPT_MAX = 5000
VSCODE_URL_DELAY = 15.0  # (the new window must be connected, Claude running, when the panel is asked for)
HANDOFF_POLL = 5.0  # seconds between asking an interactive agent's machine whether it was handed off
HANDOFF_MISSES = 12  # failed asks in a row (a minute) before the wait gives up


class Unreachable(core.CrabError):
    """ssh could not reach the machine (or it did not answer in time)."""


def alias(name: str) -> str:
    return f"{ALIAS_PREFIX}{name}"


def config_file() -> Path:
    return core.ssh_dir() / "config"


def _fwd(path: Path) -> str:
    return str(path).replace("\\", "/")


def _ssh_config_text() -> str:
    key, hosts = core.ssh_path(core.ssh_dir() / "id_ed25519"), core.ssh_path(core.ssh_dir() / "known_hosts")
    lines = ["# Generated by crab-student. Do not edit: rewritten on every launch, start and list.", ""]
    for rec in core.all_records():
        if ssh := rec.get("ssh"):
            lines += [
                f"Host {alias(rec['name'])}",
                f"  HostName {ssh['host']}",
                f"  Port {ssh['port']}",
                "  User root",
                f"  IdentityFile {key}",
                "  IdentitiesOnly yes",
                f"  UserKnownHostsFile {hosts}",
                f"  HostKeyAlias {alias(rec['name'])}",
                "  StrictHostKeyChecking accept-new",
                "  ServerAliveInterval 30",
                "  ServerAliveCountMax 4",
                "  BatchMode yes",
                "",
            ]
    return "\n".join(lines)


def _ssh_files():
    """The lock on the ssh config and known_hosts, which every agent shares (parallel launches write them)."""
    return core.locked("_ssh-files", wait=60)


def write_ssh_config() -> None:
    """Regenerate the host entries (one per agent with an address) that ~/.ssh/config includes."""
    with (
        _ssh_files()
    ):  # (the records are read inside it: a process that read them earlier must not write last)
        config_file().parent.mkdir(parents=True, exist_ok=True)
        tmp = config_file().with_name(f"config.{os.getpid()}.tmp")
        tmp.write_text(_ssh_config_text(), encoding="utf-8")
        core.replace(tmp, config_file())


def set_address(rec: dict, inst: dict) -> bool:
    """Take the machine's current ssh address (Vast may change the port on a restart); True if it changed."""
    from crab_student import vast

    addr = vast.address(inst)
    new = {"host": addr[0], "port": addr[1]} if addr else None
    if not new or new == rec.get("ssh"):
        return False
    rec["ssh"] = new
    return True


def forget_host_key(name: str) -> None:
    """A new machine for this name has a new host key."""
    hosts = core.ssh_dir() / "known_hosts"
    with _ssh_files():
        if hosts.exists() and (keygen := core.tool("ssh-keygen")):
            core.run([keygen, "-R", alias(name), "-f", str(hosts)], check=False)


def ssh_cmd(name: str, *, tty: bool = False) -> list[str]:
    ssh = core.tool("ssh")
    if not ssh:
        raise core.CrabError("ssh was not found: install the OpenSSH client and try again.")
    return [ssh, "-F", str(config_file()), *(["-t", "-o", "BatchMode=no"] if tty else []), alias(name)]


def _remote_command(args: list[str]) -> str:
    return f"cd {REMOTE_DIR} && {PY} cs.py {' '.join(shlex.quote(a) for a in args)}"


def remote(name: str, args: list[str], *, input: bytes | None = None, timeout: float = 60) -> dict:
    """Run `cs.py <args>` on the machine: the JSON object it prints last."""
    cmd = [*ssh_cmd(name), "-o", "ConnectTimeout=15", _remote_command(args)]
    try:
        p = subprocess.run(cmd, input=input or b"", capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise Unreachable(
            f"{name} did not answer within {timeout:.0f} s over ssh. Try again in a minute, or see "
            f"crab-student status {name}."
        ) from None
    out, err = p.stdout.decode("utf-8", "replace"), p.stderr.decode("utf-8", "replace")
    if p.returncode == 255:
        raise Unreachable(
            f"could not reach {name} over ssh ({core.last_line(err)}). Try again in a minute, or see "
            f"crab-student status {name}."
        )
    try:
        data = json.loads(core.last_line(out))
    except ValueError:
        raise core.CrabError(f"{name} gave an unexpected answer: {core.last_line(err or out)}") from None
    if p.returncode != 0 and isinstance(data, dict) and data.get("error"):
        raise core.CrabError(f"{name}: {data['error']}")
    return data


def reachable(name: str, addr: tuple[str, int] | None = None) -> bool:
    """ssh answers: the agent's machine through its alias, or the machine at `addr` (one of the machines racing
    for a launch: its host key goes to a throwaway file, since only the winner's is kept under the alias)."""
    ssh = ssh_cmd(name)
    if addr:
        key, hosts = core.ssh_dir() / "id_ed25519", core.ssh_dir() / "known_hosts_racing"
        ssh = [ssh[0], "-F", "none", "-p", str(addr[1]), "-i", str(key), "-o", "IdentitiesOnly=yes",
               "-o", f"UserKnownHostsFile={_fwd(hosts)}", "-o", "StrictHostKeyChecking=no", "-o", "BatchMode=yes",
               "-o", "LogLevel=ERROR", f"root@{addr[0]}"]  # fmt: skip
    cmd = [*ssh, "-o", "ConnectTimeout=8", "true"]
    try:
        return subprocess.run(cmd, capture_output=True, timeout=20).returncode == 0
    except subprocess.TimeoutExpired:
        return False


def _tar_add(tar: tarfile.TarFile, name: str, data: bytes, mode: int) -> None:
    info = tarfile.TarInfo(name)
    info.size, info.mode, info.mtime, info.uname, info.gname = len(data), mode, time.time(), "root", "root"
    tar.addfile(info, io.BytesIO(data))


def bundle(extra: dict[str, tuple[bytes, int]], fake_claude: bool = False) -> bytes:
    """A tar.gz of the machine code (the fake Claude only for a launch that uses it) plus generated files, each
    with its mode (secrets are 0600 from the start)."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for path in sorted(REMOTE_SRC.iterdir()):
            if path.name == "fake_claude.py" and not fake_claude:
                continue
            if path.is_file() and not path.name.startswith(".") and path.suffix != ".pyc":
                _tar_add(
                    tar,
                    path.name,
                    path.read_bytes().replace(b"\r\n", b"\n"),
                    0o755 if path.suffix == ".py" else 0o644,
                )
        for name, (data, mode) in extra.items():
            _tar_add(tar, name, data, mode)
    return buf.getvalue()


def upload_and_setup(
    name: str, data: bytes, on_line: Callable[[str], None], timeout: float = 3600
) -> list[str]:
    """One ssh call: unpack the bundle, run setup (which installs the project's dependencies too), pass its
    "step i/N ..." lines on as they come; setup's warnings. Anything but setup's own answer (a lost connection,
    a timeout) is Unreachable: the launch can continue."""
    cmd = [
        *ssh_cmd(name),
        "-o",
        "ConnectTimeout=15",
        f"mkdir -p {REMOTE_DIR} && tar -xzf - -C {REMOTE_DIR} --no-same-owner && {_remote_command(['setup'])}",
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    err: list[bytes] = []

    def feed() -> None:
        try:
            proc.stdin.write(data)
            proc.stdin.close()
        except OSError:
            pass

    threads = [
        threading.Thread(target=feed, daemon=True),
        threading.Thread(target=lambda: err.append(proc.stderr.read()), daemon=True),
    ]
    for t in threads:
        t.start()
    timer = threading.Timer(timeout, proc.kill)
    timer.start()
    last = ""
    try:
        for raw in proc.stdout:
            line = raw.decode("utf-8", "replace").strip()
            if line.startswith("step "):
                on_line(line)
            if line:
                last = line
        proc.wait()
    finally:
        timer.cancel()
    for t in threads:
        t.join(5)
    try:
        result = json.loads(last)
    except ValueError:
        stderr = b"".join(err).decode("utf-8", "replace")
        raise Unreachable(
            f"the upload and setup on {name} did not finish ({core.last_line(stderr or last)})."
        ) from None
    if not result.get("ok"):
        raise core.CrabError(
            f"setup failed at step {result.get('step')} ({result.get('label')}): {result.get('error')}", 5
        )
    return result.get("warnings") or []


# ---- terminals -----------------------------------------------------------------------------------


def interactive() -> bool:
    return sys.stdin.isatty() and sys.stdout.isatty()


def open_one(name: str) -> int:
    argv = [*ssh_cmd(name, tty=True), "agent-attach"]
    if interactive():
        print(f"Attaching to {name} (detach: Ctrl-b d - the agent keeps running).", flush=True)
        return subprocess.call(argv)
    if os.name == "nt" and (wt := core.tool("wt")):
        subprocess.Popen([wt, "-w", "new", "new-tab", "--title", name, *argv])
        print(f"Opened {name} in a new Windows Terminal window.")
        return 0
    raise core.CrabError(f'open needs a terminal: run "crab-student open {name}" in your terminal.', 2)


def open_launch_window(name: str) -> bool:
    """A window that follows the launch of NAME (`crab-student open NAME`), then shows the agent: a tab in the
    Windows Terminal window named crab-student (made if missing, so launches side by side collect there), or a
    Terminal window on macOS (its tabs cannot be scripted without extra permissions). False when no window could
    be opened (another system, or no terminal program)."""
    command = [sys.executable, "-m", "crab_student", "open", name]
    try:
        if os.name == "nt" and (wt := core.tool("wt")):
            subprocess.Popen([wt, "-w", "crab-student", "new-tab", "--title", name, *command])
            return True
        if sys.platform == "darwin" and (osascript := core.tool("osascript")):
            text = shlex.join(command).replace("\\", "\\\\").replace('"', '\\"')
            script = f'tell application "Terminal"\n  do script "{text}"\n  activate\nend tell'
            subprocess.Popen([osascript, "-e", script])
            return True
    except OSError:
        return False
    return False


def _wt_column(names: list[str]) -> list[str]:
    """Further panes under the focused one, sized so the column ends up with equal heights."""
    args, m = [], len(names) + 1
    for k, name in enumerate(names, start=1):
        args += [
            ";",
            "split-pane",
            "-H",
            "--size",
            f"{(m - k) / (m - k + 1):.3f}",
            "--title",
            name,
            *ssh_cmd(name, tty=True),
            "agent-attach",
        ]
    return args


def open_all(names: list[str]) -> int:
    """Every running agent side by side: one Windows Terminal window with two columns, or a local tmux
    session (prefix Ctrl-a, so Ctrl-b goes through to the agent's own tmux)."""
    if os.name == "nt":
        wt = core.tool("wt")
        if not wt:
            raise core.CrabError(
                "open --all needs Windows Terminal (wt). Install it from the Microsoft Store, or open "
                "agents one at a time: crab-student open NAME"
            )
        half = math.ceil(len(names) / 2)
        left, right = names[:half], names[half:]
        args = ["-w", "new", "new-tab", "--title", left[0], *ssh_cmd(left[0], tty=True), "agent-attach"]
        if right:
            args += [
                ";",
                "split-pane",
                "-V",
                "--title",
                right[0],
                *ssh_cmd(right[0], tty=True),
                "agent-attach",
            ]
            args += [";", "move-focus", "left"]
        args += _wt_column(left[1:])
        if right:
            args += [";", "move-focus", "right", *_wt_column(right[1:])]
        subprocess.Popen([wt, *args])
        print(f"Opened {len(names)} agent{'s' if len(names) > 1 else ''} in a new Windows Terminal window.")
        return 0
    return _tmux_all(names)


def _tmux_all(names: list[str]) -> int:
    tmux = core.tool("tmux")
    if not tmux:
        raise core.CrabError(
            "open --all needs tmux on this computer (e.g. brew install tmux, or apt install tmux). "
            "Or open agents one at a time: crab-student open NAME"
        )
    if not interactive():
        raise core.CrabError(
            'open --all needs a terminal: run "crab-student open --all" in your terminal.', 2
        )
    conf = core.ssh_dir() / "tmux-local.conf"
    conf.write_text(
        "set -g prefix C-a\nunbind C-b\nbind C-a send-prefix\nset -g mouse on\n"
        "set -g pane-border-status top\nset -g pane-border-format ' #{pane_title} '\n",
        encoding="utf-8",
    )
    base = [tmux, "-L", "crab-student", "-f", str(conf)]
    env = {k: v for k, v in os.environ.items() if k != "TMUX"}  # (works from inside the user's own tmux too)
    core.run([*base, "kill-session", "-t", "agents"], env=env, check=False)
    for i, name in enumerate(names):
        command = shlex.join([*ssh_cmd(name, tty=True), "agent-attach"])
        core.run(
            [*base, "new-session", "-d", "-s", "agents", command]
            if i == 0
            else [*base, "split-window", "-t", "agents", command],
            env=env,
        )
        core.run([*base, "select-pane", "-t", "agents", "-T", name], env=env)
        core.run([*base, "select-layout", "-t", "agents", "tiled"], env=env)
    return subprocess.call([*base, "attach", "-t", "agents"], env=env)


def local_vscode() -> str | None:
    """The commit of VS Code on this computer (the second line of `code --version`), for the machine to fetch the
    matching server ahead of the first connect."""
    code = core.tool("code")
    if not code:
        return None
    try:
        lines = subprocess.run(
            [code, "--version"], capture_output=True, text=True, timeout=30
        ).stdout.splitlines()
    except (OSError, subprocess.SubprocessError):
        return None
    commit = lines[1].strip() if len(lines) > 1 else ""
    return commit if re.fullmatch(r"[0-9a-f]{40}", commit) else None


def open_vscode(rec: dict, status: dict | None = None) -> int:
    """The machine in VS Code (Remote-SSH, the repo folder). For an interactive agent not handed off yet, also
    the Claude panel, with the task typed in but not sent, once VS Code is connected."""
    code = core.tool("code")
    if not code:
        raise core.CrabError(
            "VS Code's 'code' command was not found. In VS Code, run \"Shell Command: Install "
            "'code' command in PATH\" (on Windows it comes with the installer)."
        )
    name, folder = rec["name"], rec["repo"]["dir"]
    remember_linux_host(name)
    subprocess.Popen([code, "--remote", f"ssh-remote+{alias(name)}", folder])
    status = status or agent_status(rec)
    if status.get("frontend") != "vscode":
        print(f"Opening {name} in VS Code ({folder}). Its terminal shows the agent (tmux).")
        return 0
    print(
        f"Opening {name} in VS Code ({folder}). In a few seconds the task is typed into the Claude panel: check "
        "it and press Enter. To leave the agent working on its own when you are done, type /handoff in the chat "
        '(or "/handoff autonomous <what to do next>").',
        flush=True,
    )
    time.sleep(VSCODE_URL_DELAY)
    # (through the OS URL handler: on Windows `code` is a batch file, which mangles the % escapes)
    webbrowser.open(CLAUDE_URL + urllib.parse.quote(_task_prompt(name), safe=""))
    return 0


def wait_for_handoff(name: str) -> bool:
    """Wait until the interactive agent is handed off to tmux, asking its machine every few seconds: True then;
    False when the machine cannot be asked for a minute, or the user closes the wait with Ctrl+C."""
    print(
        f"{name} is working in VS Code; this window becomes the agent's terminal after /handoff (Ctrl+C to close).",
        flush=True,
    )
    misses = 0
    try:
        while True:
            try:
                if remote(name, ["status"], timeout=20).get("frontend") == "tmux":
                    return True
                misses = 0
            except core.CrabError as e:
                misses += 1
                if misses >= HANDOFF_MISSES:
                    print(f"Stopped waiting: {e.message}")
                    return False
            time.sleep(HANDOFF_POLL)
    except KeyboardInterrupt:
        return False


def remember_linux_host(name: str) -> None:
    """Tell VS Code the agent's host runs Linux (remote.SSH.remotePlatform), so Remote - SSH does not ask, and
    drop the entries of agents that are gone. A file that is not plain JSON (VS Code allows comments) is left
    alone, and the user is told why VS Code asks."""
    path = core.vscode_settings_file()
    if not path.parent.exists():
        return
    settings = core.read_vscode_settings(path)
    if settings is None:
        print(
            f"VS Code will ask which platform {name}'s machine runs: pick Linux. ({path} has comments, so "
            "crab-student does not edit it; without them, it records each agent's platform.)"
        )
        return
    platforms = settings.get(REMOTE_PLATFORM, {})
    if not isinstance(platforms, dict):
        return
    live = {alias(r["name"]) for r in core.all_records()} | {alias(name)}
    kept = {h: p for h, p in platforms.items() if not h.startswith(ALIAS_PREFIX) or h in live}
    wanted = {**kept, alias(name): "linux"}
    if wanted != platforms:
        core.write_vscode_settings(path, {**settings, REMOTE_PLATFORM: wanted})


def agent_status(rec: dict) -> dict:
    """The machine's status; `frontend` (where the agent's Claude works now: a hand-off moves it to tmux) comes
    from the record when the machine cannot be asked."""
    try:
        st = remote(rec["name"], ["status"], timeout=20)
    except core.CrabError:
        st = {}
    return {
        **st,
        "frontend": st.get("frontend") or ("vscode" if rec.get("mode") == "interactive" else "tmux"),
    }


def _task_prompt(name: str) -> str:
    """The brief, as the user would type it to Claude (the extension takes up to PROMPT_MAX characters: a longer
    brief is pointed to instead)."""
    brief = core.agents_dir() / f"{name}.brief.md"
    text = brief.read_text(encoding="utf-8").strip() if brief.exists() else ""
    if not text or len(text) > PROMPT_MAX:
        return "The task is in /root/BRIEF.md: read it, then let's start."
    return text
